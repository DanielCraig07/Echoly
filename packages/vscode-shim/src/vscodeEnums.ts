/**
 * vscode 官方枚举的**取值表**。
 *
 * 为什么要单独一份、而且要**一次补全**：枚举几乎都出现在扩展最容易踩到的地方 ——
 * 模块顶层或 `activate()` 的第一行（`ConfigurationTarget.Workspace`、`FileType.Directory`、
 * `LogLevel.Info`…）。shim 上少一个枚举，扩展不是「这个功能不好用」，而是
 * `Cannot read properties of undefined (reading 'Workspace')`：**主模块直接加载失败**，
 * 界面上只剩一句「已安装，但激活失败」。
 *
 * 实测两个案例：
 * - `openai.chatgpt`（Codex）在 `out/extension.js` 顶层就写
 *   `dv.ConfigurationTarget.Workspace`，缺 `ConfigurationTarget` → 整个扩展起不来，
 *   视图列表因此是空的；
 * - `esbenp.prettier-vscode@12` 在 `activate()` 里取 `LanguageStatusSeverity`。
 *
 * 枚举是纯数据、没有行为，少一个补一个没有代价；零散地「谁崩了就补谁」只会让下一台
 * 扩展再崩一次。所以这里按 `@types/vscode`（1.125.0）把**全部**枚举原样落下来，
 * 取值与官方逐字一致 —— 取值错了同样致命（见下面 UIKind）。
 *
 * 注意：`createAPI()` 里不要再单列枚举，这份是唯一来源。
 */

